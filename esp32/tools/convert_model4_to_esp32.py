"""Convert the Module 4 Elastic Net models to C headers for the ESP32.

Usage (from the project root):

    python esp32/tools/convert_model4_to_esp32.py

Reads
    models/model4_energy_arrival_soc.json        from export_model4_models.py
    esp32/tools/vectors/model4_demo_trips.json   from export_model4_models.py
Writes
    esp32/firmware/SparkEV_Integrated/model4_esp32_generated.h
        energy consumption and arrival SOC models (scaler + linear weights)
    esp32/firmware/SparkEV_Integrated/model4_driver_vectors.h
        the trip features of the two demo drivers
"""
import json
import math
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[2]
FIRMWARE = PROJECT_ROOT / "esp32" / "firmware" / "SparkEV_Integrated"

models = json.load(open(PROJECT_ROOT / "models" / "model4_energy_arrival_soc.json"))
demo = json.load(open(PROJECT_ROOT / "esp32" / "tools" / "vectors" / "model4_demo_trips.json"))


def cpp_float(value):
    value = float(value)
    if math.isnan(value):
        return "NAN"
    s = format(value, ".9g")
    if "e" not in s.lower() and "." not in s:
        s += ".0"
    return s + "f"


def c_array(name, values):
    return f"static const float {name}[{len(values)}] = {{{','.join(cpp_float(v) for v in values)}}};\n"


def model_block(prefix, m):
    return (
        f"#define {prefix.upper()}_NUM_FEATURES {len(m['features'])}\n"
        f"#define {prefix.upper()}_INTERCEPT {cpp_float(m['intercept'])}\n"
        f"// features: {', '.join(m['features'])}\n"
        + c_array(f"{prefix}_mean", m["mean"])
        + c_array(f"{prefix}_scale", m["scale"])
        + c_array(f"{prefix}_coef", m["coef"])
    )


header = f"""#pragma once

// ============================================================
// SparkEV Model 4 - Energy consumption and arrival SOC
// Automatically generated by esp32/tools/convert_model4_to_esp32.py
//
// Elastic Net models: y = intercept + sum(coef * (x - mean) / scale)
//   energy:  energy consumption of the trip [kWh/km] (Stable-23 features)
//   arrival: battery SOC at arrival (0-1), from the first 50 % of the trip
// ============================================================

{model_block("m4_energy", models["energy"])}
{model_block("m4_arrival", models["arrival_soc_50"])}
static inline float model4_linear(
    const float* x, int n, const float* mean, const float* scale,
    const float* coef, float intercept)
{{
    float y = intercept;
    for (int i = 0; i < n; i++) {{
        y += coef[i] * (x[i] - mean[i]) / scale[i];
    }}
    return y;
}}

// Active energy weights. They point at the flash weights above until an
// on-device federated learning round installs updated weights (fl_runtime.h).
static const float* m4_energy_coef_active = m4_energy_coef;
static float m4_energy_intercept_active = M4_ENERGY_INTERCEPT;

// Energy consumption [kWh/km]
static inline float model4_energy(const float* x)
{{
    return model4_linear(x, M4_ENERGY_NUM_FEATURES, m4_energy_mean,
                         m4_energy_scale, m4_energy_coef_active, m4_energy_intercept_active);
}}

// Arrival SOC [%], clipped to 0-100
static inline float model4_arrival_soc_pct(const float* x)
{{
    float soc = model4_linear(x, M4_ARRIVAL_NUM_FEATURES, m4_arrival_mean,
                              m4_arrival_scale, m4_arrival_coef, M4_ARRIVAL_INTERCEPT);
    if (soc < 0.0f) soc = 0.0f;
    if (soc > 1.0f) soc = 1.0f;
    return soc * 100.0f;
}}
"""
(FIRMWARE / "model4_esp32_generated.h").write_text(header)

vectors = """#ifndef MODEL4_DRIVER_VECTORS_H
#define MODEL4_DRIVER_VECTORS_H

// ============================================================
// SparkEV Model 4 driver-specific inputs
// Automatically generated by esp32/tools/convert_model4_to_esp32.py
// from esp32/tools/vectors/model4_demo_trips.json
//
// Each demo driver is one real Munich trip (TUM dataset) that the
// arrival SOC model did not see during training.
// ============================================================

"""
for driver, d in sorted(demo.items()):
    r = d["reference"]
    vectors += (
        f"// Driver {driver}: {d['trip']}, expected {r['energy_kwh_per_km']:.6f} kWh/km, "
        f"arrival SOC {r['arrival_soc'] * 100:.4f} %\n"
        + c_array(f"MODEL4_DRIVER{driver}_ENERGY_INPUT",
                  [d["energy_features"][f] for f in models["energy"]["features"]])
        + c_array(f"MODEL4_DRIVER{driver}_ARRIVAL_INPUT",
                  [d["arrival_features"][f] for f in models["arrival_soc_50"]["features"]])
        + "\n"
    )
vectors += "#endif\n"
(FIRMWARE / "model4_driver_vectors.h").write_text(vectors)
print("written: model4_esp32_generated.h, model4_driver_vectors.h")
