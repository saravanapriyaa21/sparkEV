"""Generate the ESP32 header for on-device federated learning.

Usage (from the project root, after esp32/tools/export_fl_setup.py):

    python esp32/tools/convert_fl_to_esp32.py

Reads models/fl/*.json, *.npz and writes
esp32/firmware/SparkEV_Integrated/fl_esp32_generated.h with

  - the training settings of every task (learning rate, epochs, batch, loss)
  - the Module 1 federated MLP (it is trained on the car; Module 1 predictions
    stay with the XGBoost model)
  - the Module 3 federated MLP, which is also the Module 3 predictor on the car
    (first layer frozen, layers 2-3 trained), and its input for each demo car
  - each demo car's local training data (it never leaves the car)

The Module 2 and Module 4 starting weights are the ones already in
model2_esp32_generated.h and model4_esp32_generated.h.
"""
import json
import os

import numpy as np

PROJECT_ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
FL_DIR = os.path.join(PROJECT_ROOT, "models", "fl")
OUT = os.path.join(PROJECT_ROOT, "esp32", "firmware", "SparkEV_Integrated", "fl_esp32_generated.h")
DRIVERS = (17, 24)
LOSS = {"mse": "FL_LOSS_MSE", "pinball": "FL_LOSS_PINBALL", "cross_entropy": "FL_LOSS_CE"}


def f(x):
    s = f"{float(np.float32(x)):.9g}"
    assert np.isfinite(float(x)), "non-finite value"
    if not any(ch in s for ch in ".e"):
        s += ".0"
    return s + "f"


def arr(name, values, ctype="float", per_line=8):
    v = np.asarray(values).ravel()
    if ctype == "float":
        items = [f(x) for x in v]
    else:
        items = [str(int(x)) for x in v]
    lines = [", ".join(items[i:i + per_line]) for i in range(0, len(items), per_line)]
    return f"static const {ctype} {name}[{len(v)}] = {{\n    " + ",\n    ".join(lines) + "\n};\n"


def load(name):
    return json.load(open(os.path.join(FL_DIR, f"{name}_fl.json"))), np.load(os.path.join(FL_DIR, f"{name}_fl.npz"))


def train_defines(p, c):
    out = (f"#define {p}_LR {f(c['lr'])}\n#define {p}_EPOCHS {c['local_epochs']}\n"
           f"#define {p}_BATCH {c['batch']}\n")
    if "loss" in c:
        out += f"#define {p}_LOSS {LOSS[c['loss']]}\n"
    return out


def car_data(p, z, y_type="float"):
    out = ""
    for d in DRIVERS:
        X, y = z[f"car{d}_X"], z[f"car{d}_y"]
        out += f"#define {p}_CAR{d}_N {len(y)}\n"
        out += arr(f"{p.lower()}_car{d}_x", X)
        out += arr(f"{p.lower()}_car{d}_y", y, "int8_t" if y_type == "int" else "float", 16)
    return out


parts = ["""// ============================================================
// SparkEV - on-device federated learning
// Generated by esp32/tools/convert_fl_to_esp32.py from models/fl/
// Do not edit by hand.
// ============================================================

#pragma once
#include <math.h>
#include <stdint.h>

"""]

# ---------------------------------------------------------------- Module 1
c, z = load("m1")
blk = np.concatenate([z[f"G{i}"].ravel() for i in range(6)])
n_ex = sum(z[f"G{i}"].size for i in range(4))
parts.append(f"""// ------------------------------------------------------------
// Module 1: battery stress MLP, FedPer ({c['sizes'][0]}-32-16-1)
// {c['source']}
// Weights in one block: W0 b0 W1 b1 (shared base, exchanged) | W2 b2 (personal head)
// Car data: first 75 % of the windows of a held-out trip
//   driver 17: {c['demo']['17']['trip']}, driver 24: {c['demo']['24']['trip']}
// ------------------------------------------------------------
#define FL_M1_IN {c['sizes'][0]}
#define FL_M1_EXCHANGE {n_ex}
#define FL_M1_TOTAL {blk.size}
""" + train_defines("FL_M1", c) + arr("fl_m1_factory", blk) + car_data("FL_M1", z) + "\n")

# ---------------------------------------------------------------- Module 2
for task, p in (("charge", "FL_M2C"), ("urgency", "FL_M2U")):
    c, z = load(f"m2_{task}")
    s = f"""// ------------------------------------------------------------
// Module 2 {task}: {c['strategy']} MLP {'-'.join(map(str, c['sizes']))}, server optimiser FedAdam
// Starting weights: model2_esp32_generated.h. Car data: the demo user's own training sessions
//   driver 17: {c['demo']['17']['user']}, driver 24: {c['demo']['24']['user']}
// ------------------------------------------------------------
"""
    s += train_defines(p, c)
    if c["loss"] == "pinball":
        s += f"#define {p}_Q {f(c['q'])}\n"
    if c.get("class_weights"):
        s += arr(f"{p.lower()}_class_weights", c["class_weights"])
    if c["personal_layers"]:
        for d in DRIVERS:
            s += arr(f"{p.lower()}_car{d}_head", np.concatenate([z[f"car{d}_head_0"].ravel(), z[f"car{d}_head_1"].ravel()]))
    s += car_data(p, z, "int" if c["loss"] == "cross_entropy" else "float")
    parts.append(s + "\n")

# ---------------------------------------------------------------- Module 3
c, z = load("m3")
upper = np.concatenate([z[f"G{i}"].ravel() for i in range(2, 6)])
s = f"""// ------------------------------------------------------------
// Module 3: SOH forecasting MLP, FedAvg ({c['sizes'][0]}-64-32-1). Predicts the SOH
// change over the next 10 cycles (scaled); forecast = SOH now + change.
// {c['source']}
// Layer 1 stays frozen on the car (Adam training of its {c['sizes'][0]}x64 weights
// would need ~366 KB RAM); layers 2-3 are trained and exchanged.
// Car data: first half of the cycles of an independent test battery
//   driver 17: {c['demo']['17']['battery']}, driver 24: {c['demo']['24']['battery']}
// ------------------------------------------------------------
#define FL_M3_IN {c['sizes'][0]}
#define FL_M3_H1 64
#define FL_M3_EXCHANGE {upper.size}
#define FL_M3_DELTA_MEAN {f(c['delta_mean'])}
#define FL_M3_DELTA_STD {f(c['delta_std'])}
""" + train_defines("FL_M3", c)
s += arr("fl_m3_w0", z["G0"]) + arr("fl_m3_b0", z["G1"]) + arr("fl_m3_factory_upper", upper)
for d in DRIVERS:
    info = c["demo"][str(d)]
    s += f"// driver {d}: newest cycle {info['seg_num']} of {info['battery']}\n"
    s += f"#define FL_M3_CAR{d}_SOH_NOW {f(info['soh_now'])}\n"
    s += arr(f"fl_m3_car{d}_now", z[f"car{d}_now_X"])
s += car_data("FL_M3", z)
parts.append(s + "\n")

# ---------------------------------------------------------------- Module 4
c, z = load("m4")
s = f"""// ------------------------------------------------------------
// Module 4: energy Elastic Net, FedAvg (proximal gradient, alpha {c['alpha']}, l1_ratio {c['l1_ratio']})
// Starting weights: model4_esp32_generated.h. Inputs scaled with the deployed scaler.
// Car data: trips of client {c['demo']['17']['client']} (driver 17) / {c['demo']['24']['client']} (driver 24)
// of the notebook's 5-client partition
// ------------------------------------------------------------
#define FL_M4_FEATURES {c['n_features']}
#define FL_M4_EXCHANGE {c['n_features'] + 1}
#define FL_M4_ALPHA {f(c['alpha'])}
#define FL_M4_L1_RATIO {f(c['l1_ratio'])}
""" + train_defines("FL_M4", c) + car_data("FL_M4", z)
parts.append(s)

open(OUT, "w").write("".join(parts))
print(f"written: {os.path.relpath(OUT, PROJECT_ROOT)} ({os.path.getsize(OUT) / 1e6:.2f} MB source)")
